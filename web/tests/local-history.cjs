const assert = require('node:assert/strict');
const { harness, deferred, tick, mounted } = require('./cloud-harness.cjs');
const empty = { draft: {text:'',images:[],files:[],mentions:[],replyTo:null}, pending:null };
const cloud = Array.from({length:10},(_,i)=>({id:`cloud-${i}`,position:String(i+1),text:`message ${i}`,attachments:[],sealed:{version:1}}));
async function setup() {
  const routes = new Map([['llmn-local-chat-route:["https://example.test/me","group"]','local']]);
  return harness(empty,true,routes,undefined,undefined,({api})=>{
    api.localView=async()=>{throw new Error('Agent stopped');};
    api.respond=async path=>path==='/chat/init' ? {self:{id:'me'},contacts:[],conversations:[{id:'group',kind:'direct'}],cursor:'1'} : {messages:cloud,hasMore:true,latestPosition:'10'};
  });
}
(async()=>{
  const h=await setup();
  let p=h.render();
  assert.equal(p.page.messages.length,10,'saved local route reads ten encrypted cloud records');
  assert.equal(p.localSelected,true,'read fallback preserves send route');
  assert.equal(p.localUnavailable,true);
  await p.history(true); assert.match(h.calls.at(-1).path,/before=1/);
  await h.api.event();
  assert.ok(h.calls.some(c=>c.path.includes('limit=100')),'SSE still refreshes cloud history after local failure');
  h.api.localView=async()=>({human:{id:'me'},ai:{id:'ai'},conversation:{id:'group'},messages:[{id:'unsynced',position:'1',text:'cached',attachments:[],local:{synced:false}}],syncState:'pending'});
  h.render().onBottom(false);
  const previous=h.render().page;
  await h.poll(500);
  assert.equal(h.render().page,previous,'poll recovery does not overwrite a scrolled cloud page');
  h.render().onBottom(true);
  await h.poll(500);
  assert.equal(h.render().page.messages[0].id,'unsynced');
  assert.equal(h.render().localUnavailable,false);
  h.api.localView=async()=>{throw new Error('Agent stopped again');};
  await h.poll(500);
  assert.ok(h.render().page.messages.some(m=>m.id==='unsynced'),'retains in-memory unsynced messages');
  assert.equal(h.calls.filter(c=>c.local||c.method==='POST').length,0,'history never sends commands');
  const paging=await setup(), older=deferred();
  await paging.render().history(); paging.render();
  paging.api.respond=()=>older.promise;
  // No onBottom(false): requesting older records itself protects the read position.
  const pagination=paging.render().history(true);
  paging.api.localView=async()=>({human:{id:'me'},ai:{id:'ai'},conversation:{id:'group'},messages:[{id:'local-latest',position:'11',attachments:[]}],syncState:'synced'});
  await paging.poll(500);
  older.resolve({messages:[{id:'older',position:'0',attachments:[]}],hasMore:false,latestPosition:'10'});
  await pagination;
  assert.equal(paging.render().page.messages[0].id,'older','slow explicit pagination survives local polling without caller changing bottom state');
  assert.equal(paging.render().page.messages.some(m=>m.id==='local-latest'),false);
  for (const cloudFails of [false,true]) {
    const racing=await setup(), delayed=deferred();
    const local=messages=>({human:{id:'me'},ai:{id:'ai'},conversation:{id:'group'},messages,syncState:'synced'});
    const unsynced={id:'kept-local',position:'1',text:'not uploaded',attachments:[],local:{synced:false}};
    racing.api.localView=async()=>local([unsynced]);
    await racing.render().history(); racing.render();
    racing.api.localView=async()=>{throw new Error('one failed local request');};
    racing.api.respond=()=>delayed.promise;
    await racing.poll(500);
    assert.ok(racing.render().page.messages.some(m=>m.id==='kept-local'),'one failed local request keeps unsynced memory while cloud is pending');
    const recovered={id:'newer-synced',position:'11',text:'newer',attachments:[],local:{synced:true}};
    racing.api.localView=async()=>local([unsynced,recovered]);
    await racing.poll(500);
    assert.ok(racing.render().page.messages.some(m=>m.id==='newer-synced'),'next poll recovers while cloud request is still pending');
    if(cloudFails) delayed.reject(new Error('stale cloud failure'));
    else delayed.resolve({messages:cloud,hasMore:false,latestPosition:'10'});
    await tick(); await tick();
    assert.deepEqual(Array.from(racing.render().page.messages,m=>m.id),['kept-local','newer-synced'],'older cloud completion cannot overwrite recovered synced or unsynced records');
    assert.equal(racing.render().localUnavailable,false);
    assert.equal(racing.render().historyError,'','stale cloud failure cannot mark the recovered local view as failed');
  }
  const failed=await setup(); failed.api.respond=async()=>{throw new Error('cloud offline');};
  await failed.render().history(); assert.match(failed.render().historyError,/cloud offline/);
  failed.api.respond=async()=>({messages:cloud,hasMore:false});
  await failed.render().history(); assert.equal(failed.render().historyError,'');
  const late=await setup(), wait=deferred(); late.api.respond=path=>path.includes('/new-chat/')?{messages:[],hasMore:false,latestPosition:'0'}:wait.promise;
  const reading=late.render().history(); await tick();
  late.render().selectConversation('new-chat'); late.render();
  wait.resolve({messages:cloud,hasMore:false}); await reading;
  assert.equal(late.render().active,'new-chat');
  assert.equal(late.render().page?.messages.length ?? 0,0,'late response cannot overwrite a different chat');
  const locked=await setup(), pending=deferred(); locked.api.respond=()=>pending.promise;
  const previousLocked=locked.render().page;
  const loading=locked.render().history(); await tick(); locked.unmount();
  pending.resolve({messages:cloud,hasMore:false}); await loading;
  assert.equal(locked.render().page,previousLocked,'late response cannot restore locked state');
  console.log('PASS: offline history paginates, recovers local view, retains unsynced messages and rejects stale reads');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>{for(const h of mounted)h.unmount();});
