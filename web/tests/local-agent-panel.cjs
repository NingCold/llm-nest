const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const React = require('react');
const { createRoot } = require('react-dom/client');
const { act } = React;
const source = ts.transpileModule(fs.readFileSync(require.resolve('../src/cloud/LocalAgentPanel.tsx'), 'utf8'), { compilerOptions: { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const deferred = () => { let resolve, reject; const promise = new Promise((a,b) => { resolve=a; reject=b; }); return {promise,resolve,reject}; };
const status = { configured:true,running:true,nodeId:'node',configuration:null,pairing:null,aiIds:['ai'],error:null };
(async () => {
  const { Window } = await import('happy-dom');
  const window = new Window();
  Object.assign(globalThis, { window, document:window.document, IS_REACT_ACT_ENVIRONMENT:true });
  const calls=[], timers=new Set(), exports={};
  vm.runInNewContext(source, { exports, setInterval(fn) { timers.add(fn); return fn; }, clearInterval(fn) { timers.delete(fn); }, require(name) {
    if(name==='@tauri-apps/api/core') return {invoke(command) { if(command==='local_agent_models')return Promise.resolve({providers:[]}); const pending=deferred(); calls.push({command,...pending}); return pending.promise; }};
    if(name==='./LocalAiEncryption')return {LocalAiEncryption:()=>null};
    if(name==='./api')return {request:()=>{throw Error('unexpected HTTP');}};
    return require(name);
  }});
  const root=createRoot(document.body.appendChild(document.createElement('div')));
  let owner='human';
  const render=()=>React.createElement(React.StrictMode,null,React.createElement(exports.LocalAgentPanel,{ai:{account:{id:'ai',name:'AI'},node:null,bindingVersion:'1'},operatorId:owner,changed:async()=>{},openChat:async()=>{}}));
  const flush=async(fn=()=>{})=>act(async()=>{fn(); await new Promise(setImmediate);});
  await flush(()=>root.render(render()));
  assert.equal(calls.length,1,'StrictMode replay must retain a single in-flight native read');
  await flush(()=>{for(let i=0;i<100;i++)for(const timer of timers)timer();});
  assert.equal(calls.length,1,'slow native status must not accumulate queue entries');
  await flush(()=>calls[0].resolve(status));
  assert.match(document.body.textContent,/正在检查/,'first StrictMode lifetime result must be ignored');
  await flush(()=>{for(const timer of timers)timer();});
  await flush(()=>calls[1].resolve(status));
  assert.match(document.body.textContent,/本机 Agent 正在运行/);
  await flush(()=>{for(const timer of timers)timer();}); // old status in flight
  const old=calls[2];
  await flush(()=>Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='停止本机 Agent').click());
  assert.equal(calls[3].command,'local_agent_stop');
  await flush(()=>{for(let i=0;i<100;i++)for(const timer of timers)timer();});
  assert.equal(calls.length,4,'mutation must suppress new polling');
  await flush(()=>calls[3].resolve({...status,running:false}));
  await flush(()=>old.reject(Error('obsolete status error')));
  assert.ok(!document.body.textContent.includes('obsolete status error'),'late poll errors cannot overwrite action feedback');
  await flush(()=>{for(const timer of timers)timer();});
  const oldOwner=calls[4];
  owner='other-human';
  await flush(()=>root.render(render()));
  assert.equal(calls.length,5,'owner switch must not overlap the old native read');
  await flush(()=>oldOwner.resolve({...status,pairing:{userCode:'OLD-CODE',pairingId:'old',expiresAt:'2030-01-01'}}));
  assert.ok(!document.body.textContent.includes('OLD-CODE'),'old owner pairing code must never render');
  await flush(()=>{for(const timer of timers)timer();});
  assert.equal(calls.length,6,'new owner can refresh once old read settles');
  await flush(()=>calls[5].resolve(status));
  await flush(()=>Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='停止本机 Agent').click());
  const oldAction=calls[6];
  owner='third-human';
  await flush(()=>root.render(render()));
  await flush(()=>oldAction.resolve({...status,pairing:{userCode:'OLD-ACTION',pairingId:'old',expiresAt:'2030-01-01'}}));
  assert.ok(!document.body.textContent.includes('OLD-ACTION'),'late mutation response cannot populate a new owner panel');
  await flush(()=>root.unmount());
  assert.equal(timers.size,0);
  console.log('PASS: mounted LocalAgentPanel single-flight, StrictMode, action/poll ordering and owner-switch late results');
})().catch(error=>{console.error(error);process.exitCode=1;});
