const assert=require('node:assert/strict');
const {harness}=require('./draft-harness.cjs');
const image=(id='old')=>({id,name:'中文🙂.png',mime:'image/png',byteLength:5,data:'AP+JUE4='});
const owner='https://example.test/me';
const blank=()=>({draft:{text:'',requestId:null},pending:null});
(async()=>{
 const h=harness();await h.database.load(owner,['chat','group']);
 const reference={actorId:'ai',selection:{conversationId:'group',sources:[{messageId:'source',revision:'2'}]}};
 const pending={text:'original',requestId:'retry-original',images:[image()],mentions:['ai'],replyTo:'reply',reference};
 const edited={...pending,text:'later input',requestId:null,images:[image(),image('new')]};
 await h.database.save(owner,'chat',{draft:edited,pending});
 await h.database.save(owner,'group',{draft:{...edited,images:[image('group')]},pending:null});
 const reopened=h.reopen(),records=await reopened.database.load(owner,['chat','group']);
 assert.deepEqual(JSON.parse(JSON.stringify(records.chat)),{draft:{...edited,files:[]},pending:{...pending,files:[]}});
 assert.equal(records.group.draft.images[0].id,'group');
 assert.equal((await reopened.database.load('https://other.test/me',['chat'])).chat,undefined,'servers remain separate');
 assert.equal((await reopened.database.load('https://example.test/other',['chat'])).chat,undefined,'accounts remain separate');
 await reopened.database.save(owner,'chat',blank());
 assert.equal((await h.reopen().database.load(owner,['chat'])).chat.draft.images.length,0,'removed blobs do not return');
 // Existing records in the unchanged IndexedDB store are readable after relocation.
 assert.equal(h.persistence.DRAFT_DATABASE,'llm-nest-social-drafts');
 const legacy=harness(),key=legacy.persistence.LEGACY_DRAFT_KEY;
 legacy.values.set(key,JSON.stringify({chat:{text:'legacy',requestId:'legacy-request',mentions:['ai'],replyTo:'reply'},unknown:{text:'retain',requestId:null}}));
 assert.equal((await legacy.database.load(owner,['chat'])).chat.pending.requestId,'legacy-request');
 assert.deepEqual(Object.keys(JSON.parse(legacy.values.get(key))),['unknown']);
 await legacy.database.save(owner,'chat',blank());
 legacy.values.set(key,JSON.stringify({chat:{text:'must not return',requestId:null}}));
 assert.equal((await legacy.reopen().database.load(owner,['chat'])).chat.draft.text,'');
 const corrupt=harness();corrupt.values.set(key,'{broken');await assert.rejects(corrupt.database.load(owner,['chat']));assert.equal(corrupt.values.get(key),'{broken');
 const first=harness();await first.database.load(owner,['chat','other']);
 const second=first.reopen();await second.database.load(owner,['chat','other']);
 await first.database.save(owner,'chat',{draft:{text:'first page',requestId:null},pending:null});
 await assert.rejects(second.database.save(owner,'chat',{draft:{text:'second page',requestId:null},pending:null}),/另一个页面/);
 assert.equal((await first.reopen().database.load(owner,['chat'])).chat.draft.text,'first page');
 await second.database.save(owner,'other',{draft:{text:'other window',requestId:null},pending:null});
 // Storage failure is surfaced and cannot replace previously committed text.
 const failed=first.reopen();await failed.database.load(owner,['chat']);failed.database.open=async()=>{throw new Error('disk quota')};
 await assert.rejects(failed.database.save(owner,'chat',blank()),/disk quota/);
 assert.equal((await first.reopen().database.load(owner,['chat'])).chat.draft.text,'first page');
 console.log('PASS: chat binary draft reopen, immutable pending identity, attachment removal, account/server/window isolation, legacy migration/tombstones, corrupt data, concurrent writers and write failures');
})().catch(error=>{console.error(error);process.exitCode=1});
